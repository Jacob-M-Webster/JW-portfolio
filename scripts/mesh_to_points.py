"""Car point sampling (docs/05-3d-and-motion.md section 2.3).

    python scripts/mesh_to_points.py --inspect          # writes docs/asset-report.md
    python scripts/mesh_to_points.py --preview DIR      # D10 and roof previews, outside the repo
    python scripts/mesh_to_points.py [--out DIR]        # writes scene-points.bin and .json

Reads the purchased model from assets-private/ and never copies it. Only the
derived, quantized points leave this script.
"""

import argparse
import hashlib
import json
import sys
import zipfile
from pathlib import Path

import numpy as np

import scene_common as c
from make_quadruped import make_quadruped, make_rings

PRIVATE = c.ROOT / "assets-private" / "low-poly-car-jaguar-i-pace-waymo-driver"
OBJ = PRIVATE / "Low Poly Car - Jaguar I-PACE Waymo Driver" / "Waymo_Taxi.obj"
GLTF = PRIVATE / "low_poly_car_-_jaguar_i-pace_waymo_driver" / "scene.gltf"
ZIP = PRIVATE / "low-poly-car-jaguar-i-pace-waymo-driver" / "source" / "Waymo_Taxi.zip"
REPORT = c.ROOT / "docs" / "asset-report.md"

# Decisions recorded in docs/asset-report.md and the decision log.
SOURCE = OBJ  # D10
BODY = "s_0018"
# Islands of the body group, keyed by (triangle count, bbox min y in OBJ units).
# Cabin shell, two seats, dashboard, panel, steering wheel, column, pedal box.
INTERIOR = {(490, 18.1), (136, 16.5), (86, 14.2), (36, 20.2), (256, 33.6), (52, 33.4), (42, 26.1)}
INTERIOR_COUNT = 8  # the seats are two islands with the same key
# Roof sensor rack with dome, inner dome piece, front-fender sensor pods (two islands, one key).
SENSORS = {(1490, 59.5), (24, 65.7), (291, 36.4)}
SENSOR_COUNT = 4
ROOF = "generic"  # "pods" (sensors as modeled) or "generic" (sensors replaced by ROOF_BAR)
# Generic low roof bar on the glass roof (top y 64.3), OBJ units: a crossbar on two feet.
ROOF_BAR = [
    ((0.0, 67.4, -8.0), (44.0, 3.2, 8.0)),
    ((-16.0, 65.2, -8.0), (5.0, 2.0, 5.0)),
    ((16.0, 65.2, -8.0), (5.0, 2.0, 5.0)),
]
GENERATED = "2026-10-19"  # fixed so reruns are byte-identical


def to_scene(v):
    """OBJ axes (Y up, front +Z) to scene axes (Y up, front +X)."""
    return np.stack([v[:, 2], v[:, 1], -v[:, 0]], axis=1)


def island_id(key):
    return (key[0], key[1][1])


def car_parts(groups, roof, keep_interior=False):
    """The body without interior islands (and without the sensor units when generic)."""
    parts, dropped = [], {"interior": 0, "sensors": 0}
    for name, (v, t) in groups.items():
        if name != BODY:
            parts.append((v, t))
            continue
        for key, tri in c.islands(v, t):
            if island_id(key) in INTERIOR and not keep_interior:
                dropped["interior"] += 1
            elif island_id(key) in SENSORS and roof == "generic":
                dropped["sensors"] += 1
            else:
                parts.append((v, tri))
    if not keep_interior and dropped["interior"] != INTERIOR_COUNT:
        sys.exit(f"expected {INTERIOR_COUNT} interior islands, found {dropped['interior']}")
    if roof == "generic":
        if dropped["sensors"] != SENSOR_COUNT:
            sys.exit(f"expected {SENSOR_COUNT} sensor islands, found {dropped['sensors']}")
        parts += [c.box(center, size) for center, size in ROOF_BAR]
    return parts


def sample_car(groups, roof=ROOF, keep_interior=False, n=c.N_POINTS, seed=c.SEED):
    rng = np.random.default_rng(seed)
    return c.normalize(to_scene(c.sample_surface(car_parts(groups, roof, keep_interior), n, rng)))


# ---------------------------------------------------------------- inspect


def inspect():
    lines = [
        "# Asset report",
        "",
        "Generated by `scripts/mesh_to_points.py --inspect`. Names and numbers only; no mesh data.",
        "The raw files stay in `assets-private/` (gitignored) and never ship (`docs/05` section 2.1).",
        "",
        "## Files",
        "",
        "| File | Bytes | Role |",
        "|---|---|---|",
    ]
    for f in sorted(PRIVATE.rglob("*")):
        if f.is_file():
            rel = f.relative_to(PRIVATE).as_posix()
            role = {
                ".obj": "Mesh (candidate)",
                ".gltf": "Mesh (candidate)",
                ".bin": "glTF buffer",
                ".fbx": "Mesh, same model (not read: needs assimp)",
                ".usdz": "Mesh, same model (not read: needs usd-core)",
                ".zip": "Archive of the OBJ",
                ".txt": "License notice",
            }.get(f.suffix.lower(), "Texture (never used)")
            lines.append(f"| `{rel}` | {f.stat().st_size:,} | {role} |")

    def table(rows, title, axes_note):
        out = ["", f"## {title}", "", axes_note, ""]
        out += ["| Group | Faces | Triangles | Vertices | Min (x, y, z) | Max (x, y, z) |", "|---|---|---|---|---|---|"]
        for name, faces, (v, t) in rows:
            lo, hi = c.bounds(v)
            fmt = lambda a: "(" + ", ".join(f"{x:.2f}" for x in a) + ")"
            out.append(f"| `{name}` | {faces:,} | {len(t):,} | {len(v):,} | {fmt(lo)} | {fmt(hi)} |")
        return out

    obj = c.read_obj(OBJ)
    faces = c.obj_face_counts(OBJ)
    lines += table(
        [(k, faces[k], obj[k]) for k in obj],
        "Waymo_Taxi.obj",
        "Y up, front toward +Z, model units. Polygon faces as written, fan-triangulated for sampling.",
    )
    gl = c.read_gltf(GLTF)
    lines += table(
        [(k, len(t), (v, t)) for k, (v, t) in gl.items()],
        "scene.gltf",
        "World space after node transforms (the Sketchfab root matrix turns Z up into Y up). "
        "Meshes were merged by material on export, so the OBJ's group names are lost.",
    )

    with zipfile.ZipFile(ZIP) as z:
        inner = z.read("Waymo_Taxi.obj")
    loose = OBJ.read_bytes()
    def counts(data):
        lines = data.splitlines()
        stamp = next(l for l in lines if l.startswith(b"# File Created")).decode().split(": ", 1)[1]
        return sum(l.startswith(b"v ") for l in lines), sum(l.startswith(b"f ") for l in lines), stamp

    zv, zf, zt = counts(inner)
    lv, lf, lt = counts(loose)
    lines += [
        "",
        "## Archive",
        "",
        f"`source/Waymo_Taxi.zip` holds one `Waymo_Taxi.obj` of {len(inner):,} bytes (read in memory, not extracted). "
        f"It is a different export of the same model: {zv:,} vertices and {zf:,} faces, created {zt}, against the loose OBJ's "
        f"{lv:,} vertices and {lf:,} faces, created {lt}. It is not used.",
        "",
        "## Islands of the body group",
        "",
        f"`{BODY}` is {len(c.islands(*obj[BODY]))} connected mesh islands. The ones the pipeline names, keyed by "
        "(triangle count, bbox min y) in `scripts/mesh_to_points.py`:",
        "",
        "| Triangles | Min (x, y, z) | Max (x, y, z) | What it is | Used |",
        "|---|---|---|---|---|",
    ]
    what = {
        (490, 18.1): ("Cabin interior shell", "Excluded (interior)"),
        (136, 16.5): ("Seat", "Excluded (interior)"),
        (86, 14.2): ("Dashboard", "Excluded (interior)"),
        (36, 20.2): ("Interior panel", "Excluded (interior)"),
        (256, 33.6): ("Steering wheel", "Excluded (interior)"),
        (52, 33.4): ("Steering column", "Excluded (interior)"),
        (42, 26.1): ("Pedal box", "Excluded (interior)"),
        (1490, 59.5): ("Roof sensor rack with dome", "Kept with `ROOF = pods`; removed with `generic`"),
        (24, 65.7): ("Inner dome piece", "Kept with `ROOF = pods`; removed with `generic`"),
        (291, 36.4): ("Front-fender sensor pod", "Kept with `ROOF = pods`; removed with `generic`"),
    }
    for key, _ in c.islands(*obj[BODY]):
        if island_id(key) in what:
            name, use = what[island_id(key)]
            fmt = lambda a: "(" + ", ".join(f"{x:.1f}" for x in a) + ")"
            lines.append(f"| {key[0]:,} | {fmt(key[1])} | {fmt(key[2])} | {name} | {use} |")
    lines += [
        "",
        "Identified by rendering each island in its own color against the rest of the body (scratchpad previews, not committed).",
        "",
        "## Exclusion list",
        "",
        "| What | Why |",
        "|---|---|",
        "| The eight interior islands above | Interior (section 2.3 step 2). With them gone no interior geometry remains, so the visibility filter (step 3) is not needed and `rtree` is not installed |",
        "| Textures (all) | Never read; geometry only, so no logo or livery reaches the points |",
        "",
        "Kept: `Object003` is the glass (windshield, side windows, panoramic roof, light lenses), not interior; without it the windows read as holes. "
        "`Object006` and `Object007` are the wheel pairs.",
        "Not present, so nothing to exclude: ground or shadow planes (the ambient-occlusion ground exists only as a texture), cameras, lights.",
        "",
        "## Roof variants",
        "",
        "`ROOF = \"pods\"` samples the sensors as modeled. `ROOF = \"generic\"` removes the roof rack, the inner dome and both fender pods, "
        "and samples a plain low crossbar on two feet (`ROOF_BAR`, on the glass roof) instead, keeping the point count.",
        "",
        "## Decisions",
        "",
        f"- D10 source: `{SOURCE.name}`.",
        f"- Roof: `{ROOF}`.",
        "- Forward axis: OBJ +Z (the low hood) maps to scene +X; OBJ +X maps to scene -Z.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))


# ---------------------------------------------------------------- preview


def preview(out_dir):
    out_dir = Path(out_dir).resolve()
    if c.ROOT in out_dir.parents or out_dir == c.ROOT:
        sys.exit("preview: write previews outside the repo")
    light, _ = c.token_colors()
    ramp = [c.hex_rgb(light[k]) for k in ("ramp-ground", "ramp-mid", "ramp-top")]
    obj = c.read_obj(OBJ)
    gl = c.read_gltf(GLTF)
    variants = {
        # D10 compares like with like: both files whole, interior included.
        "d10-obj": lambda: sample_car(obj, roof="pods", keep_interior=True),
        # The glTF's world space matches the OBJ's axes once the root matrix is applied.
        "d10-gltf": lambda: c.normalize(
            to_scene(c.sample_surface(list(gl.values()), c.N_POINTS, np.random.default_rng(c.SEED)))
        ),
        "roof-pods": lambda: sample_car(obj, roof="pods"),
        "roof-generic": lambda: sample_car(obj, roof="generic"),
    }
    for name, make in variants.items():
        p = make()
        rgb = c.height_colors(p[:, 1], p[:, 1].max(), *ramp)
        views = []
        for yaw in (0.0, c.YAW_DEG):
            img = c.rasterize(p, rgb, np.ones(len(p)), 800, 600, 2.4, yaw=yaw)
            views.append(c.flatten(img, light["viewport"]))
        c.write_png(out_dir / f"{name}.png", np.concatenate(views, axis=1))
        print("preview:", out_dir / f"{name}.png")


# ---------------------------------------------------------------- build


def build(out_dir):
    car = sample_car(c.read_obj(SOURCE))
    quad = make_quadruped(c.SEED + 1)
    rings = make_rings()

    both = np.concatenate([car, quad])
    lo, hi = both.min(axis=0), both.max(axis=0)
    car = car[c.morton_order(car, lo, hi)]
    quad = quad[c.morton_order(quad, lo, hi)]
    perm = np.random.default_rng(c.SEED + 2).permutation(c.N_POINTS)
    car, quad = car[perm], quad[perm]

    blobs = [c.quantize(car, 1.0), c.quantize(quad, 1.0), c.quantize(rings, 3.0)]
    names = [("car", 1.0), ("quad", 1.0), ("rings", 3.0)]
    shapes, offset = [], 0
    for (name, scale), q in zip(names, blobs):
        shapes.append({"name": name, "offsetBytes": offset, "points": len(q), "scale": scale})
        offset += q.nbytes
    inputs = {
        "source": SOURCE.name,
        "interior": sorted(INTERIOR),
        "roof": ROOF,
        "sensors": sorted(SENSORS) if ROOF == "generic" else None,
        "roofBar": ROOF_BAR if ROOF == "generic" else None,
        "points": c.N_POINTS,
        "rings": c.N_RINGS,
        "seed": c.SEED,
    }
    meta = {
        "version": 1,
        "count": c.N_POINTS,
        "quant": c.QUANT,
        "shapes": shapes,
        "sourceHash": hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest(),
        "generated": GENERATED,
    }
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "scene-points.bin").write_bytes(b"".join(q.tobytes() for q in blobs))
    # newline="\n": the bytes must not depend on the OS (Windows text mode writes CRLF).
    (out_dir / "scene-points.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")
    for f in ("scene-points.bin", "scene-points.json"):
        data = (out_dir / f).read_bytes()
        print(f"{f}: {len(data):,} bytes, sha256 {hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--inspect", action="store_true")
    ap.add_argument("--preview", metavar="DIR")
    ap.add_argument("--out", default=str(c.MODELS))
    args = ap.parse_args()
    if args.inspect:
        inspect()
    elif args.preview:
        preview(args.preview)
    else:
        build(args.out)
